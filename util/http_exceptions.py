"""Application HTTP errors, including those translated into WebSocket messages.

Add fixed status/detail pairs here. Each call creates a fresh FastAPI exception::

    raise HttpError.ROOM_NOT_FOUND.exception()
    raise HttpError.TOO_MANY_ATTEMPTS.exception(headers={"Retry-After": "30"})

Authentication and retry headers stay explicit at the call site. Framework-generated
validation/authentication errors and direct Response/JSONResponse bodies are separate.
"""
from enum import Enum

from fastapi import HTTPException


class HttpError(Enum):
    # HTTP 400
    INVALID_INFORMATION_TYPE = (400, 'Invalid information type')
    TOO_MANY_INVALID_MESSAGES = (400, 'TOO_MANY_INVALID_MESSAGES')

    # HTTP 401
    AUTH_MESSAGE_REQUIRED = (401, 'AUTH_MESSAGE_REQUIRED')
    AUTH_REQUIRED = (401, 'AUTH_REQUIRED')
    CHAT_GUEST_SESSION_INVALID = (401, 'CHAT_GUEST_SESSION_INVALID')
    INVALID_TOKEN = (401, 'INVALID_TOKEN')
    LOGIN_REQUIRED = (401, 'LOGIN_REQUIRED')

    # HTTP 403
    CHAT_ADMIN_REQUIRED = (403, 'CHAT_ADMIN_REQUIRED')
    CHAT_RESTRICTED = (403, 'CHAT_RESTRICTED')
    INVALID_ROOM_PASSWORD = (403, 'INVALID_ROOM_PASSWORD')
    MARKER_OWNER_REQUIRED = (403, 'MARKER_OWNER_REQUIRED')
    PARTY_INVITATIONS_UNAVAILABLE = (403, 'PARTY_INVITATIONS_UNAVAILABLE')
    PARTY_INVITATION_FORBIDDEN = (403, 'PARTY_INVITATION_FORBIDDEN')
    PARTY_MEMBERSHIP_CHANGED = (403, 'PARTY_MEMBERSHIP_CHANGED')
    PARTY_MEMBERSHIP_REQUIRED = (403, 'PARTY_MEMBERSHIP_REQUIRED')
    PARTY_MEMBER_KICKED = (403, 'PARTY_MEMBER_KICKED')
    PARTY_OWNER_REQUIRED = (403, 'PARTY_OWNER_REQUIRED')
    PARTY_ROOM_LOCKED = (403, 'PARTY_ROOM_LOCKED')
    REGISTERED_USER_REQUIRED = (403, 'REGISTERED_USER_REQUIRED')
    ROOM_LOCKED = (403, 'ROOM_LOCKED')

    # HTTP 404
    CHAT_MESSAGE_NOT_FOUND = (404, 'CHAT_MESSAGE_NOT_FOUND')
    CHAT_USER_NOT_FOUND = (404, 'CHAT_USER_NOT_FOUND')
    DESKTOP_RELEASE_NOT_FOUND = (404, 'DESKTOP_RELEASE_NOT_FOUND')
    MAP_ALIASES_NOT_FOUND = (404, 'MAP_ALIASES_NOT_FOUND')
    MARKER_NOT_FOUND = (404, 'MARKER_NOT_FOUND')
    MEMBER_NOT_FOUND = (404, 'MEMBER_NOT_FOUND')
    OFFER_NOT_FOUND = (404, 'Offer not found')
    PARTY_INVITATION_NOT_FOUND = (404, 'PARTY_INVITATION_NOT_FOUND')
    ROOM_NOT_FOUND = (404, 'ROOM_NOT_FOUND')
    SEASON_NOT_FOUND = (404, 'Season not found')
    TRADER_NOT_FOUND = (404, 'Trader not found')
    USER_NOT_FOUND = (404, 'USER_NOT_FOUND')

    # HTTP 408
    AUTH_TIMEOUT = (408, 'AUTH_TIMEOUT')
    HEARTBEAT_TIMEOUT = (408, 'HEARTBEAT_TIMEOUT')

    # HTTP 409
    CAPACITY_BELOW_MEMBER_COUNT = (409, 'CAPACITY_BELOW_MEMBER_COUNT')
    CHAT_ALREADY_REPORTED = (409, 'CHAT_ALREADY_REPORTED')
    CHAT_REQUEST_ID_CONFLICT = (409, 'CHAT_REQUEST_ID_CONFLICT')
    MARKER_VERSION_CONFLICT = (409, 'MARKER_VERSION_CONFLICT')
    MEMBER_COLOR_IN_USE = (409, 'MEMBER_COLOR_IN_USE')
    MEMBER_NOT_KICKED = (409, 'MEMBER_NOT_KICKED')
    OWNER_MUST_LEAVE_OR_TRANSFER = (409, 'OWNER_MUST_LEAVE_OR_TRANSFER')
    PARTY_ALREADY_JOINED = (409, 'PARTY_ALREADY_JOINED')
    PARTY_INVITATION_ALREADY_HANDLED = (409, 'PARTY_INVITATION_ALREADY_HANDLED')
    PARTY_INVITATION_DUPLICATED = (409, 'PARTY_INVITATION_DUPLICATED')
    PARTY_ROOM_FULL = (409, 'PARTY_ROOM_FULL')
    RAID_STATE_STALE = (409, 'RAID_STATE_STALE')
    RAID_TIMER_EXPIRED = (409, 'RAID_TIMER_EXPIRED')
    ROOM_FULL = (409, 'ROOM_FULL')
    ROOM_MARKER_LIMIT = (409, 'ROOM_MARKER_LIMIT')

    # HTTP 410
    PARTY_INVITATION_EXPIRED = (410, 'PARTY_INVITATION_EXPIRED')
    PARTY_ROOM_CLOSED = (410, 'PARTY_ROOM_CLOSED')
    RESOURCE_REMOVED = (410, 'Removed')
    ROOM_CLOSED = (410, 'ROOM_CLOSED')

    # HTTP 413
    MESSAGE_TOO_LARGE = (413, 'MESSAGE_TOO_LARGE')

    # HTTP 422
    CHAT_CANNOT_BLOCK_SELF = (422, 'CHAT_CANNOT_BLOCK_SELF')
    CHAT_INVALID_CHANNEL = (422, 'CHAT_INVALID_CHANNEL')
    CHAT_INVALID_CURSOR = (422, 'CHAT_INVALID_CURSOR')
    FLOOR_NOT_IN_MAP = (422, 'FLOOR_NOT_IN_MAP')
    FLOOR_NOT_IN_ROOM_MAP = (422, 'FLOOR_NOT_IN_ROOM_MAP')
    INVALID_MAP = (422, 'INVALID_MAP')
    LIVE_MAP_NOT_AVAILABLE = (422, 'LIVE_MAP_NOT_AVAILABLE')
    PARTY_CANNOT_INVITE_SELF = (422, 'PARTY_CANNOT_INVITE_SELF')
    RAID_MAP_UNRESOLVED = (422, 'RAID_MAP_UNRESOLVED')
    SEASON_MODE_REQUIRED = (422, 'season_id is only supported for pvp-season')
    TEXT_JSON_REQUIRED = (422, 'TEXT_JSON_REQUIRED')

    # HTTP 429
    CHAT_CONNECTION_LIMIT = (429, 'CHAT_CONNECTION_LIMIT')
    CHAT_CONNECT_RATE_LIMITED = (429, 'CHAT_CONNECT_RATE_LIMITED')
    CHAT_RATE_LIMITED = (429, 'CHAT_RATE_LIMITED')
    CHAT_REPEATED_MESSAGE = (429, 'CHAT_REPEATED_MESSAGE')
    PARTY_INVITATION_LIMIT = (429, 'PARTY_INVITATION_LIMIT')
    PARTY_INVITATION_RATE_LIMITED = (429, 'PARTY_INVITATION_RATE_LIMITED')
    PARTY_INVITATION_REJECT_COOLDOWN = (429, 'PARTY_INVITATION_REJECT_COOLDOWN')
    TOO_MANY_ATTEMPTS = (429, 'TOO_MANY_ATTEMPTS')
    TOO_MANY_PARTY_CONNECTIONS = (429, 'TOO_MANY_PARTY_CONNECTIONS')

    # HTTP 500
    IMAGE_PROCESSING_FAILED = (500, '이미지 처리 실패')
    IMAGE_PROCESSING_FAILED_WITH_REASON = (500, '이미지 처리 실패: {error}')
    IMAGE_STORAGE_UPLOAD_FAILED = (500, '이미지 저장소 업로드 실패: {error}')
    TRADER_LOOKUP_FAILED = (500, 'Trader lookup failed')

    # HTTP 503
    AUTH_SERVICE_UNAVAILABLE = (503, 'AUTH_SERVICE_UNAVAILABLE')
    AUTH_UNAVAILABLE = (503, 'AUTH_UNAVAILABLE')
    CHAT_GUEST_SESSION_UNAVAILABLE = (503, 'CHAT_GUEST_SESSION_UNAVAILABLE')
    CHAT_PRESENCE_UNAVAILABLE = (503, 'CHAT_PRESENCE_UNAVAILABLE')
    CHAT_RATE_LIMIT_UNAVAILABLE = (503, 'CHAT_RATE_LIMIT_UNAVAILABLE')
    DESKTOP_METADATA_UNAVAILABLE = (503, 'DESKTOP_METADATA_UNAVAILABLE')
    PARTY_RATE_LIMIT_UNAVAILABLE = (503, 'PARTY_RATE_LIMIT_UNAVAILABLE')
    PARTY_REALTIME_UNAVAILABLE = (503, 'PARTY_REALTIME_UNAVAILABLE')
    PATH_REPORT_STORAGE_UNAVAILABLE = (503, 'PATH_REPORT_STORAGE_UNAVAILABLE')
    RAID_MAP_LOOKUP_UNAVAILABLE = (503, 'RAID_MAP_LOOKUP_UNAVAILABLE')
    RAID_STATE_DATABASE_UNAVAILABLE = (503, 'RAID_STATE_DATABASE_UNAVAILABLE')
    RAID_STATE_PUBLISH_UNAVAILABLE = (503, 'RAID_STATE_PUBLISH_UNAVAILABLE')
    USER_LOOKUP_UNAVAILABLE = (503, 'USER_LOOKUP_UNAVAILABLE')

    @property
    def status_code(self) -> int:
        return self.value[0]

    @property
    def detail(self) -> str:
        return self.value[1]

    def exception(self, *, headers: dict[str, str] | None = None, **context) -> HTTPException:
        """Build a new exception, preserving per-request headers and template values."""
        detail = self.detail.format(**context) if context else self.detail
        return HTTPException(
            status_code=self.status_code,
            detail=detail,
            headers=dict(headers) if headers is not None else None,
        )

declare
    route_point_count integer;
    route_stop_count integer;
    linked_stop_count integer;
begin
    select count(*)
      into route_point_count
    from live_map_btr_route_points rp
    join live_map_btr_routes r on r.id = rp.route_id
    where r.map_id = '5704e3c2d2720bac5b8b4567'
      and r.name in ('R1 West', 'R2 West', 'R3 East', 'R4 East', 'R5 West');

    select count(*),
           count(*) filter (where rp.id is not null)
      into route_stop_count, linked_stop_count
    from live_map_btr_route_stops rs
    join live_map_btr_routes r on r.id = rs.route_id
    left join live_map_btr_route_points rp on rp.id = rs.route_point_id and rp.route_id = rs.route_id
    where r.map_id = '5704e3c2d2720bac5b8b4567'
      and r.name in ('R1 West', 'R2 West', 'R3 East', 'R4 East', 'R5 West');

    if route_point_count <> 293
       or route_stop_count <> 32
       or linked_stop_count <> 32 then
        raise exception
            'Woods BTR validation failed: points %, stops %, linked stops %',
            route_point_count,
            route_stop_count,
            linked_stop_count;
    end if;
end
$$;

